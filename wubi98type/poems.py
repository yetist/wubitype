from __future__ import annotations
from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Poem:
    number: int
    title: str
    author: str
    lines: tuple[str, ...]
    note: str = ""

    @property
    def text(self) -> str:
        return "\n".join(self.lines)

    @property
    def display_title(self) -> str:
        if self.note:
            return f"{self.title}（{self.note}）"
        return self.title

    @property
    def label(self) -> str:
        return f"{self.number:02d}  {self.display_title} · {self.author}"


